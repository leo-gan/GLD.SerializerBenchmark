#!/usr/bin/env bash
# Compile the Dagr TypeScript (src/generated/dagr/*.ts, emitted by `dagr build` from
# schemas/v2/dagr/schema.py) into one plain-ESM module the harness imports.
#
# Why a build step: the generated TS uses extension-less relative imports
# ("./dagr_reader"), which Node's native type stripping cannot resolve, and CI runs
# Node 20 (no type stripping at all). esbuild resolves the imports and strips types
# without type-checking; the output is checked in like the protobuf-es output.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
"$ROOT/node_modules/.bin/esbuild" "$ROOT/scripts/dagr-entry.js" \
  --bundle --format=esm --platform=node --target=node18 \
  --legal-comments=none \
  --banner:js="// Generated by scripts/generate-dagr.sh from src/generated/dagr/*.ts — do not edit." \
  --outfile="$ROOT/src/generated/dagr_bundle.js"
echo "[OK] wrote $ROOT/src/generated/dagr_bundle.js"
