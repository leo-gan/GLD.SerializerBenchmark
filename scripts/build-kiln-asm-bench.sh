#!/usr/bin/env bash
# Build shared libkiln_asm_bench.{a,so} and C/C++ headers from gld-kiln-asm 0.2.0
# and schemas/v2/kiln/*.json (Option A: one shared library consumed by all language harnesses).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

KILN_ASM_VERSION="${GLD_KILN_ASM_VERSION:-0.2.0}"
RELEASE_BASE="https://github.com/leo-gan/gld-kiln-asm/releases/download/${KILN_ASM_VERSION}"

OUT_DIR="$PROJECT_ROOT/build/kiln-asm"
GEN_DIR="$OUT_DIR/gen"
OBJ_DIR="$OUT_DIR/obj"
INC_DIR="$OUT_DIR/include"
VENDOR_DIR="$OUT_DIR/vendor-${KILN_ASM_VERSION}"
SCHEMA_DIR="$PROJECT_ROOT/schemas/v2/kiln"

AS="${AS:-as}"
LD="${LD:-ld}"
AR="${AR:-ar}"
READELF="${READELF:-readelf}"
PYTHON="${PYTHON:-python3}"

SCHEMAS=(
  message
  document
  telemetry
  strings
  event
  table_columns
  table_project
  nested_table
  signal
  request
)

# 1. Locate gld-kiln-asm core artifacts (env override -> local sibling -> GitHub Release)
CORE_A=""
CORE_H=""
CODEGEN=""

resolve_local_dir() {
  local dir="$1"
  if [[ -f "$dir/include/kiln_asm.h" && -f "$dir/codegen/gld_kilngen_asm.py" ]]; then
    if [[ ! -f "$dir/lib/libkiln_asm.a" ]]; then
      echo "[kiln-asm] Building libkiln_asm.a in $dir"
      make -C "$dir" MODE=cabi lib/libkiln_asm.a
    fi
    CORE_A="$dir/lib/libkiln_asm.a"
    CORE_H="$dir/include/kiln_asm.h"
    CODEGEN="$dir/codegen/gld_kilngen_asm.py"
    return 0
  fi
  return 1
}

if [[ -n "${GLD_KILN_ASM_DIR:-}" ]]; then
  resolve_local_dir "$GLD_KILN_ASM_DIR" || {
    echo "ERROR: GLD_KILN_ASM_DIR='$GLD_KILN_ASM_DIR' missing kiln_asm.h or gld_kilngen_asm.py" >&2
    exit 1
  }
elif resolve_local_dir "$PROJECT_ROOT/../gld-kiln-asm"; then
  echo "[kiln-asm] Using local sibling $PROJECT_ROOT/../gld-kiln-asm"
else
  mkdir -p "$VENDOR_DIR"
  if [[ ! -f "$VENDOR_DIR/libkiln_asm.a" || ! -f "$VENDOR_DIR/kiln_asm.h" || ! -f "$VENDOR_DIR/gld_kilngen_asm.py" ]]; then
    echo "[kiln-asm] Downloading gld-kiln-asm ${KILN_ASM_VERSION} release assets..."
    for f in libkiln_asm.a kiln_asm.h gld_kilngen_asm.py SHA256SUMS; do
      curl -fsSL -L -o "$VENDOR_DIR/$f" "${RELEASE_BASE}/$f"
    done
    (cd "$VENDOR_DIR" && sha256sum -c --ignore-missing SHA256SUMS)
  fi
  CORE_A="$VENDOR_DIR/libkiln_asm.a"
  CORE_H="$VENDOR_DIR/kiln_asm.h"
  CODEGEN="$VENDOR_DIR/gld_kilngen_asm.py"
fi

# 2. Generate Assembly & C11 headers from schemas/v2/kiln/*.json
rm -rf "$GEN_DIR" "$OBJ_DIR" "$INC_DIR"
mkdir -p "$GEN_DIR" "$OBJ_DIR/core" "$INC_DIR"

SCHEMA_ARGS=()
for s in "${SCHEMAS[@]}"; do
  SCHEMA_ARGS+=(--schema "$SCHEMA_DIR/${s}.json")
done

"$PYTHON" "$CODEGEN" --prefix bench --emit-map "${SCHEMA_ARGS[@]}" --out "$GEN_DIR"

# 3. Assemble generated codecs (x86-64 GAS, PIC-clean)
GEN_OBJS=()
for s in "${SCHEMAS[@]}"; do
  "$AS" --64 -o "$OBJ_DIR/${s}.o" "$GEN_DIR/${s}.s"
  GEN_OBJS+=("$OBJ_DIR/${s}.o")
done

# 4. Build combined static archive libkiln_asm_bench.a (core + generated)
(cd "$OBJ_DIR/core" && "$AR" x "$CORE_A")
rm -f "$OUT_DIR/libkiln_asm_bench.a"
"$AR" rcs "$OUT_DIR/libkiln_asm_bench.a" "$OBJ_DIR"/core/*.o "${GEN_OBJS[@]}"

# 5. Build combined zero-libc shared library libkiln_asm_bench.so
VERSION_MAP="$GEN_DIR/message.map"
rm -f "$OUT_DIR/libkiln_asm_bench.so"
"$LD" -shared -Bsymbolic \
  --version-script="$VERSION_MAP" \
  -z noexecstack -z relro -z now \
  -soname libkiln_asm_bench.so \
  -o "$OUT_DIR/libkiln_asm_bench.so" \
  "${GEN_OBJS[@]}" \
  --whole-archive "$CORE_A" --no-whole-archive

# 6. Verify ELF invariants on libkiln_asm_bench.so
if "$READELF" -d "$OUT_DIR/libkiln_asm_bench.so" | grep -qE 'NEEDED|TEXTREL'; then
  echo "ERROR: libkiln_asm_bench.so has NEEDED or TEXTREL!" >&2
  "$READELF" -d "$OUT_DIR/libkiln_asm_bench.so" >&2
  exit 1
fi
if "$READELF" --wide --dyn-syms "$OUT_DIR/libkiln_asm_bench.so" \
     | awk '$4 == "FUNC" && $7 != "UND" && $8 !~ /^kiln_asm_/' | grep -q .; then
  echo "ERROR: libkiln_asm_bench.so exports unexpected non-kiln_asm_* symbols!" >&2
  "$READELF" --wide --dyn-syms "$OUT_DIR/libkiln_asm_bench.so" >&2
  exit 1
fi

# 7. Stage headers under include/kiln_bench/ so stems like signal.h / strings.h never shadow POSIX headers
mkdir -p "$INC_DIR/kiln_bench"
cp -f "$CORE_H" "$INC_DIR/kiln_asm.h"
for s in "${SCHEMAS[@]}"; do
  cp -f "$GEN_DIR/${s}.h" "$INC_DIR/kiln_bench/${s}.h"
done

{
  cat <<'EOF'
/* Generated by scripts/build-kiln-asm-bench.sh. Do not edit. */
#ifndef KILN_ASM_BENCH_H
#define KILN_ASM_BENCH_H

#include "kiln_asm.h"

#if defined(__cplusplus) && !defined(_Static_assert)
#define _Static_assert static_assert
#define KILN_ASM_BENCH_UNDEF_STATIC_ASSERT 1
#endif

EOF
  for s in "${SCHEMAS[@]}"; do
    echo "#include \"kiln_bench/${s}.h\""
  done
  cat <<'EOF'

#ifdef KILN_ASM_BENCH_UNDEF_STATIC_ASSERT
#undef _Static_assert
#undef KILN_ASM_BENCH_UNDEF_STATIC_ASSERT
#endif

#endif /* KILN_ASM_BENCH_H */
EOF
} > "$INC_DIR/kiln_asm_bench.h"

echo "[kiln-asm] Built $OUT_DIR/libkiln_asm_bench.a and $OUT_DIR/libkiln_asm_bench.so"
echo "[kiln-asm] Headers ready in $INC_DIR (kiln_asm_bench.h + ${#SCHEMAS[@]} generated schemas)"

# 8. Build shared JVM JNI bridge libkiln_asm_jni.so (used by Java and Kotlin harnesses)
CC="${CC:-cc}"
JNI_INC=""
for cand in "${JAVA_HOME:-}/include" "${HOME}/.local/jdk-21/include" /usr/lib/jvm/*/include; do
  if [[ -f "$cand/jni.h" && -d "$cand/linux" ]]; then
    JNI_INC="$cand"
    break
  fi
done
if [[ -n "$JNI_INC" && -f "$SCRIPT_DIR/kiln_asm_jni.c" ]] && command -v "$CC" >/dev/null 2>&1; then
  "$CC" -O3 -fPIC -shared -Wall -Wextra \
    -I"$INC_DIR" -I"$JNI_INC" -I"$JNI_INC/linux" \
    "$SCRIPT_DIR/kiln_asm_jni.c" "$OUT_DIR/libkiln_asm_bench.a" \
    -o "$OUT_DIR/libkiln_asm_jni.so"
  echo "[kiln-asm] Built $OUT_DIR/libkiln_asm_jni.so (using $JNI_INC)"
fi
